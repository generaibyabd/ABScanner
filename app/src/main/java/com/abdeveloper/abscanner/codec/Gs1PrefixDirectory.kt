    fun lookupCountryOrCategory(code: String): String? {
        val clean = code.trim().filter { it.isDigit() }
        if (clean.length < 3) return null

        val prefix3 = clean.substring(0, 3).toIntOrNull() ?: return null

        if (prefix3 in 0..19 || prefix3 in 30..39 || prefix3 in 60..139) return "GS1 US / Canada"
        if (prefix3 in 200..299) return "Restricted distribution (internal store use)"
        if (prefix3 in 300..379) return "GS1 France"
        if (prefix3 == 380) return "GS1 Bulgaria"
        if (prefix3 == 383) return "GS1 Slovenia"
        if (prefix3 == 385) return "GS1 Croatia"
        if (prefix3 in 400..440) return "GS1 Germany"
        if (prefix3 in 450..459 || prefix3 in 490..499) return "GS1 Japan"
        if (prefix3 in 460..469) return "GS1 Russia"
        if (prefix3 == 471) return "GS1 Taiwan"
        if (prefix3 == 474) return "GS1 Estonia"
        if (prefix3 == 480) return "GS1 Philippines"
        if (prefix3 == 489) return "GS1 Hong Kong"
        if (prefix3 in 500..509) return "GS1 United Kingdom"
        if (prefix3 in 520..521) return "GS1 Greece"
        if (prefix3 == 528) return "GS1 Lebanon"
        if (prefix3 == 529) return "GS1 Cyprus"
        if (prefix3 in 535..539) return "GS1 Ireland & Malta"
        if (prefix3 in 540..549) return "GS1 Belgium & Luxembourg"
        if (prefix3 == 560) return "GS1 Portugal"
        if (prefix3 == 569) return "GS1 Iceland"
        if (prefix3 in 570..579) return "GS1 Denmark"
        if (prefix3 in 590..599) return "GS1 Poland & Central Europe"
        if (prefix3 in 600..601) return "GS1 South Africa"
        if (prefix3 == 608) return "GS1 Bahrain"
