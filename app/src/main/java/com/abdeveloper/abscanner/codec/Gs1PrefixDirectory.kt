    fun lookupGs1ApplicationIdentifier(ai: String): String? {
        return when (ai) {
            "00" -> "SSCC (Serial Shipping Container Code)"
            "01" -> "GTIN (Global Trade Item Number)"
            "02" -> "Content GTIN"
            "10" -> "Batch / Lot Number"
            "11" -> "Production Date (YYMMDD)"
            "12" -> "Due Date (YYMMDD)"
            "13" -> "Packaging Date (YYMMDD)"
            "15" -> "Best Before Date (YYMMDD)"
            "17" -> "Expiration Date (YYMMDD)"
            "20" -> "Internal Product Variant"
            "21" -> "Serial Number"
            "30" -> "Variable Count"
            "310" -> "Net Weight (kg)"
            "37" -> "Number of Units Contained"
            "400" -> "Customer Purchase Order Number"
            "410" -> "Ship to / Deliver to Location"
            "420" -> "Ship to Postal Code"
            "421" -> "Ship to Country and Postal Code"
            "8005" -> "Price per Unit of Measure"
            else -> null
        }
    }
